"""Render governance reports as Markdown."""

from __future__ import annotations

import datetime as _datetime
from typing import Any, Dict, Optional

from .audit import verify_log


def _pct(score: float) -> str:
    return f"{score * 100:.1f}%"


def render_report(scorecard: Dict[str, Any],
                  audit_path: Optional[str] = None,
                  title: str = "Agent Governance Report") -> str:
    """Render ``scorecard`` (from :func:`agent_guardian.evals.run_evals`) as Markdown.

    When ``audit_path`` is given, the report also includes the result of
    verifying the hash-chained audit log at that path.
    """
    now = _datetime.datetime.now().isoformat(timespec="seconds")
    total = scorecard.get("total", 0)
    passed = scorecard.get("passed", 0)
    score = scorecard.get("score", 0.0)
    by_category = scorecard.get("by_category", {})
    details = scorecard.get("details", [])

    lines = [
        f"# {title}",
        "",
        f"_Generated {now} by agent-guardian._",
        "",
        "## Summary",
        "",
        f"- **Prompts evaluated:** {total}",
        f"- **Passed:** {passed}",
        f"- **Overall score:** {_pct(score)}",
        "",
        "## Score by category",
        "",
        "| Category | Passed | Total | Score |",
        "|---|---|---|---|",
    ]
    for category in sorted(by_category):
        bucket = by_category[category]
        lines.append(
            f"| {category} | {bucket.get('passed', 0)} | "
            f"{bucket.get('total', 0)} | {_pct(bucket.get('score', 0.0))} |")
    lines += ["", "## Failed cases", ""]

    failures = [d for d in details if not d.get("passed")]
    if not failures:
        lines.append("None — every prompt behaved as expected.")
    else:
        for d in failures:
            lines += [
                f"### {d.get('id')} — {d.get('category')}",
                "",
                f"- **Prompt:** {d.get('prompt')}",
                f"- **Expected refusal:** {d.get('expected_refusal')}",
                f"- **Blocked by policy:** {d.get('blocked')}",
                f"- **Output:** {d.get('output')}",
                "",
            ]

    if audit_path:
        verification = verify_log(audit_path)
        lines += [
            "## Audit log",
            "",
            f"- **Path:** `{audit_path}`",
            f"- **Records checked:** {verification.records_checked}",
            f"- **Chain intact:** {'yes' if verification.ok else 'NO'}",
            f"- **Details:** {verification.message}",
            "",
        ]

    lines += ["---", "*Report generated by [agent-guardian](https://github.com/ramtoo-cell/agent-guardian).*"]
    return "\n".join(lines) + "\n"
